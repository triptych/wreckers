import { ctx } from './dom.js';
import { W } from './geometry.js';

/* ---------- 3x5 pixel font (drawn, not typeset) ---------- */
export const FONT = {
 'A':'010101111101101','B':'110101110101110','C':'011100100100011','D':'110101101101110',
 'E':'111100110100111','F':'111100110100100','G':'011100101101011','H':'101101111101101',
 'I':'111010010010111','J':'001001001101010','K':'101101110101101','L':'100100100100111',
 'M':'101111111101101','N':'101111111111101','O':'010101101101010','P':'110101110100100',
 'Q':'010101101110011','R':'110101110101101','S':'011100010001110','T':'111010010010010',
 'U':'101101101101111','V':'101101101101010','W':'101101111111101','X':'101101010101101',
 'Y':'101101010010010','Z':'111001010100111',
 '0':'111101101101111','1':'010110010010111','2':'111001111100111','3':'111001111001111',
 '4':'101101111001001','5':'111100111001111','6':'111100111101111','7':'111001001001001',
 '8':'111101111101111','9':'111101111001111',
 '!':'010010010000010','.':'000000000000010','-':'000000111000000',' ':'000000000000000',
 ':':'000010000010000',"'":'010010000000000'
};
export function textW(s,sc){ return (s.length*4-1)*sc; }
export function drawText(s, x, y, col, sc=1){
  ctx.fillStyle = col;
  for(let i=0;i<s.length;i++){
    const g = FONT[s[i]] || FONT[' '];
    const ox = x + i*4*sc;
    for(let r=0;r<5;r++) for(let c2=0;c2<3;c2++)
      if(g[r*3+c2]==='1') ctx.fillRect(ox+c2*sc, y+r*sc, sc, sc);
  }
}
export function drawTextC(s,y,col,sc=1){ drawText(s, Math.round((W-textW(s,sc))/2), y, col, sc); }
